/** 某件家具旋转后的水平碰撞盒（ry 只取 90 的整数倍，故 AABB 精确） */
export function footprint(i) {
  const swap = (((i.ry || 0) % 360) + 360) % 360 % 180 !== 0;
  const w = swap ? (i.sd ?? i.d) : (i.sw ?? i.w);
  const d = swap ? (i.sw ?? i.w) : (i.sd ?? i.d);
  return { x0: i.x - w / 2, x1: i.x + w / 2, z0: i.z - d / 2, z1: i.z + d / 2 };
}
