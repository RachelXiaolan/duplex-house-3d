const DT = 1 / 60, TOL = 0.30, STALL = 4 / DT; // 4 秒无进展判定卡住
let fail = 0, maxJump = 0, maxDrop = 0;
const ok = (c, m) => { console.log(`  ${c ? '✓' : '✗'} ${m}`); if (!c) fail++; };

/** 走到目标点；返回 {ok, frames} */
function goto(name, tx, tz, expectY) {
  let best = Infinity, since = 0, frames = 0, prevY = p.pos.y;
  while (frames < 60 / DT) {
    const ux = tx - p.pos.x, uz = tz - p.pos.z, d = Math.hypot(ux, uz);
    if (d < TOL) break;
    p.yaw = Math.atan2(-ux / d, -uz / d);
    p.update(DT);
    const jump = Math.abs(p.pos.y - prevY);
    if (jump > maxJump) maxJump = jump;
    if (prevY - p.pos.y > maxDrop) maxDrop = prevY - p.pos.y;
    prevY = p.pos.y;
    frames++;
    if (d < best - 0.01) { best = d; since = 0; } else if (++since > STALL) break;
  }
  const dist = Math.hypot(tx - p.pos.x, tz - p.pos.z);
  const sup = supports(p.pos.x, p.pos.z);
  let nearest = null; for (const h of sup) if (nearest === null || Math.abs(h - p.pos.y) < Math.abs(nearest - p.pos.y)) nearest = h;
  const onSurface = nearest !== null && Math.abs(nearest - p.pos.y) < 0.02;   // 站在真实支撑面上
  const good = dist < TOL && onSurface && (expectY === undefined || Math.abs(p.pos.y - expectY) < 0.12);
  ok(good, `${name.padEnd(22)} → (${p.pos.x.toFixed(2)}, ${p.pos.y.toFixed(2)}, ${p.pos.z.toFixed(2)}) `
    + `偏差 ${dist.toFixed(2)}m${expectY !== undefined ? ` · Y 期望 ${expectY.toFixed(2)}` : ''}${onSurface ? '' : ' · 未贴合支撑面!'} · ${frames} 帧`);
  if (!good) { p.place(tx, tz, undefined, expectY); p.vy = 0; console.log('    ↳ 已强制归位到该航路点，继续测试后续段落'); }
  return good;
}

